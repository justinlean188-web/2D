export function generateAISuggestions(items: RankingItem[]): AISoundSuggestion[] {
  const suggestions: AISoundSuggestion[] = [];

  items.forEach((item) => {
    const titleLower = item.title.toLowerCase();
    const dur = item.duration;

    suggestions.push({
      id: `sug-${item.id}-whoosh`,
      clipId: item.id,
      effectType: 'whoosh',
      label: 'Rank Reveal Whoosh',
      offsetSec: 0.1,
      reason: 'Enhances entrance of rank in the video',
      volume: 1.0,
    });

    if (titleLower.includes('aaah') || titleLower.includes('slip') || titleLower.includes('fail')) {
      suggestions.push({
        id: `sug-${item.id}-punch`,
        clipId: item.id,
        effectType: 'punch',
        label: 'Smack Impact',
        offsetSec: Math.max(0.5, dur * 0.55),
        reason: 'Punches the comic wipeout moment',
        volume: 1.3,
      });
      suggestions.push({
        id: `sug-${item.id}-laugh`,
        clipId: item.id,
        effectType: 'laughter',
        label: 'Crowd Reaction Laugh',
        offsetSec: Math.max(0.8, dur * 0.7),
        reason: 'Viral comedy audience reaction',
        volume: 1.1,
      });
    } else {
      suggestions.push({
        id: `sug-${item.id}-impact`,
        clipId: item.id,
        effectType: 'impact',
        label: 'Heavy Water Splash',
        offsetSec: Math.max(0.5, dur * 0.6),
        reason: 'Impactful water landing',
        volume: 1.3,
      });
    }

    if (item.rank === 1) {
      suggestions.push({
        id: `sug-${item.id}-bass`,
        clipId: item.id,
        effectType: 'bass-drop',
        label: 'Ultimate #1 Champion Bass Drop',
        offsetSec: 0.2,
        reason: 'Deep bass emphasis for final #1 reveal',
        volume: 1.4,
      });
      suggestions.push({
        id: `sug-${item.id}-fanfare`,
        clipId: item.id,
        effectType: 'success',
        label: 'Grand Finale Fanfare',
        offsetSec: Math.max(0.8, dur * 0.75),
        reason: 'Celebrates the grand champion #1 moment',
        volume: 1.3,
      });
    }
  });

  return suggestions;
}

