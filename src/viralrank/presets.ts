export function generateAISuggestions(items: RankingItem[]): AISoundSuggestion[] {
  const suggestions: AISoundSuggestion[] = [];

  items.forEach((item, idx) => {
    const titleLower = item.title.toLowerCase();
    const dur = item.duration;

    // Beginning whoosh when rank appears
    suggestions.push({
      id: `sug-${item.id}-whoosh`,
      clipId: item.id,
      effectType: 'whoosh',
      label: 'Rank Reveal Whoosh',
      offsetSec: 0.1,
      reason: 'Enhances the entrance of the ranking badge and clip title',
      volume: 1.0,
    });

    // Content specific checks
    if (titleLower.includes('shot') || titleLower.includes('throw') || titleLower.includes('ball')) {
      suggestions.push({
        id: `sug-${item.id}-riser`,
        clipId: item.id,
        effectType: 'riser',
        label: 'Throw Anticipation Riser',
        offsetSec: Math.max(0.2, dur * 0.25),
        reason: 'Builds suspense while the ball or dart is in mid-air',
        volume: 0.9,
      });
      suggestions.push({
        id: `sug-${item.id}-impact`,
        clipId: item.id,
        effectType: 'impact',
        label: 'Trick Shot Landing Climax',
        offsetSec: Math.max(0.5, dur * 0.72),
        reason: 'Punches the exact moment the shot scores or hits the bullseye',
        volume: 1.3,
      });
      suggestions.push({
        id: `sug-${item.id}-cheer`,
        clipId: item.id,
        effectType: 'crowd-cheer',
        label: 'Celebration Roar',
        offsetSec: Math.max(0.8, dur * 0.78),
        reason: 'Simulates viral audience reaction after the miracle shot',
        volume: 1.1,
      });
    } else if (titleLower.includes('fail') || titleLower.includes('funny') || titleLower.includes('revenge')) {
      suggestions.push({
        id: `sug-${item.id}-punch`,
        clipId: item.id,
        effectType: 'punch',
        label: 'Bonk Comic Punch',
        offsetSec: dur * 0.6,
        reason: 'Accentuates the collision or head bonk gag',
        volume: 1.2,
      });
      suggestions.push({
        id: `sug-${item.id}-scratch`,
        clipId: item.id,
        effectType: 'record-scratch',
        label: 'Awkward Record Freeze',
        offsetSec: dur * 0.68,
        reason: 'Highlights the sudden freeze frame comedic reaction',
        volume: 1.0,
      });
      suggestions.push({
        id: `sug-${item.id}-laugh`,
        clipId: item.id,
        effectType: 'laughter',
        label: 'Comedy Chuckle',
        offsetSec: dur * 0.75,
        reason: 'Invites viewer laughter on TikTok and Shorts',
        volume: 0.9,
      });
    } else {
      suggestions.push({
        id: `sug-${item.id}-ding`,
        clipId: item.id,
        effectType: 'ding',
        label: 'Score Chime',
        offsetSec: dur * 0.65,
        reason: 'Clear audio reward when the highlight action finishes',
        volume: 1.0,
      });
    }

    // Number 1 gets a special bass drop
    if (idx === items.length - 1 || item.rank === 1) {
      suggestions.push({
        id: `sug-${item.id}-bass`,
        clipId: item.id,
        effectType: 'bass-drop',
        label: 'Top #1 Sub Bass Drop',
        offsetSec: 0.2,
        reason: 'Creates high-stakes audio impact for the ultimate #1 reveal',
        volume: 1.4,
      });
      suggestions.push({
        id: `sug-${item.id}-fanfare`,
        clipId: item.id,
        effectType: 'success',
        label: 'Grand Champion Fanfare',
        offsetSec: dur * 0.8,
        reason: 'Celebrates the final victor of the ranking video',
        volume: 1.2,
      });
    }
  });

  return suggestions;
}

